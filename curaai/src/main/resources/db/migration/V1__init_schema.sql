-- CuraAI baseline schema — PostgreSQL
-- Matches the existing entity classes exactly (BIGINT identity PKs,
-- LocalDate/LocalDateTime → DATE/TIMESTAMP without time zone).
-- Place in: src/main/resources/db/migration/V1__init_schema.sql (Flyway)

-- Enabled now so it's available once we build the RAG document/chunk
-- entities in a later migration — no vector columns yet, nothing here
-- depends on it.
CREATE EXTENSION IF NOT EXISTS vector;

-- =========================================================
-- USER
-- =========================================================

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email     VARCHAR(255) NOT NULL UNIQUE,
    password  VARCHAR(255) NOT NULL,
    role      VARCHAR(255) NOT NULL DEFAULT 'USER'
);

-- =========================================================
-- CHAT (flat history, keyed by email — matches ChatMessage as-is)
-- =========================================================

CREATE TABLE chat_messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email VARCHAR(255) NOT NULL,
    sender     VARCHAR(10)  NOT NULL,          -- "user" or "bot"
    content    TEXT         NOT NULL,
    created_at TIMESTAMP    NOT NULL
);

CREATE INDEX idx_chat_messages_user_email ON chat_messages(user_email, created_at);

-- =========================================================
-- EXERCISE
-- =========================================================

CREATE TABLE exercise_logs (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date             DATE   NOT NULL,
    activity_type    VARCHAR(255) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    calories_burned  INTEGER,
    notes            VARCHAR(255)
);

CREATE INDEX idx_exercise_logs_user_date ON exercise_logs(user_id, date);

-- =========================================================
-- NUTRITION
-- =========================================================

CREATE TABLE nutrition_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    date         DATE   NOT NULL,
    food_name    VARCHAR(255),
    meal_type    VARCHAR(255),
    calories     INTEGER NOT NULL,
    protein      INTEGER,
    carbs        INTEGER,
    fat          INTEGER,
    fiber        INTEGER,
    sugar        INTEGER,
    health_score INTEGER,
    insight      VARCHAR(1000)
);

CREATE INDEX idx_nutrition_logs_user_date ON nutrition_logs(user_id, date);

-- =========================================================
-- PRESCRIPTIONS
-- =========================================================

CREATE TABLE prescriptions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    uploaded_at TIMESTAMP NOT NULL,
    label       VARCHAR(255),
    raw_text    TEXT                            -- was LONGTEXT (MySQL-only); TEXT is unlimited in Postgres
);

CREATE INDEX idx_prescriptions_user ON prescriptions(user_id);

CREATE TABLE prescription_medications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prescription_id BIGINT NOT NULL REFERENCES prescriptions(id) ON DELETE CASCADE,
    drug_name       VARCHAR(255) NOT NULL,
    dosage          VARCHAR(255),
    frequency       VARCHAR(255),
    active          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_prescription_medications_prescription ON prescription_medications(prescription_id);

CREATE TABLE medication_doses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medication_id BIGINT NOT NULL REFERENCES prescription_medications(id) ON DELETE CASCADE,
    dose_date     DATE    NOT NULL,
    taken         BOOLEAN NOT NULL DEFAULT FALSE,
    taken_at      TIMESTAMP,
    CONSTRAINT uq_medication_dose UNIQUE (medication_id, dose_date)
);

CREATE INDEX idx_medication_doses_medication ON medication_doses(medication_id, dose_date);

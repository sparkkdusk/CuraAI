-- CuraAI RAG support — V2
-- Adds a per-user document_chunks table so chat can semantically search
-- across nutrition, exercise, and prescription history. The pgvector
-- extension was already enabled in V1; nothing new to install here.
--
-- Place in: src/main/resources/db/migration/V2__add_rag_support.sql

CREATE TABLE document_chunks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    source_type VARCHAR(20) NOT NULL,   -- NUTRITION, EXERCISE, PRESCRIPTION
    source_id   BIGINT NOT NULL,
    content     TEXT NOT NULL,
    embedding   vector(1024) NOT NULL, -- voyage-4-lite's default output size
    created_at  TIMESTAMP NOT NULL DEFAULT now()
);

-- One source record (one nutrition log, one exercise log, one prescription)
-- should only ever have one current chunk. Re-indexing deletes the old row
-- and inserts a fresh one rather than accumulating duplicates.
CREATE UNIQUE INDEX idx_document_chunks_source ON document_chunks(source_type, source_id);
CREATE INDEX idx_document_chunks_user ON document_chunks(user_id);

